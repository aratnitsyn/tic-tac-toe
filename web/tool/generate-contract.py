#!/usr/bin/env python3
"""Generate TS wire types from the checked-in public API. No validator packages."""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
schemas = json.loads((root / 'contracts/http/public.openapi.json').read_text())['components']['schemas']


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[1]
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    kind = schema.get('type')
    if kind == 'array':
        return 'Array<' + ts(schema['items']) + '>'
    if kind == 'object':
        if 'properties' not in schema:
            return 'Record<string, ' + ts(schema['additionalProperties']) + '>'
        required = schema.get('required', [])
        return '{\n' + '\n'.join('  ' + k + ('' if k in required else '?') + ': ' + ts(v) + ';'
                                   for k, v in schema['properties'].items()) + '\n}'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean'}[kind]


content = '// Generated by tool/generate-contract.py; edit contracts, then regenerate.\n'
content += '\n\n'.join('export type ' + name + ' = ' + ts(schema) + ';' for name, schema in schemas.items()) + '\n'
target = root / 'web/src/api/contract.ts'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != content:
        raise SystemExit('Wire types differ; run python3 tool/generate-contract.py')
else:
    target.write_text(content)
